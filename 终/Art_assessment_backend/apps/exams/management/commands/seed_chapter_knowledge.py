class Command(BaseCommand):
    help = "为已有章节补充知识讲解正文（幂等，--force 覆盖）"

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="覆盖已有知识讲解内容",
        )

    def handle(self, *args, **options):
        force = options["force"]
        now = timezone.now()
        updated = 0
        missing = []
        for chapter in Chapter.objects.filter(deleted_at__isnull=True):
            knowledge = CHAPTER_KNOWLEDGE.get(chapter.name)
            if not knowledge:
                missing.append(chapter.name)
                continue
            fields = []
            if force or not (chapter.description or "").strip():
                chapter.description = knowledge["description"]
                fields.append("description")
            if force or not (chapter.content or "").strip():
                chapter.content = knowledge["content"]
                fields.append("content")
            if fields:
                chapter.updated_at = now
                chapter.save(update_fields=[*fields, "updated_at"])
                updated += 1
        self.stdout.write(
            self.style.SUCCESS(f"章节知识讲解已更新 {updated} 个章节")
        )
        if missing:
            self.stdout.write(
                self.style.WARNING("以下章节没有预置讲解：" + "、".join(sorted(set(missing))))
            )
